import React, { useState, useRef, useCallback } from "react"
import { motion, AnimatePresence } from "framer-motion"
import {
  Upload,
  FileCode,
  X,
  Loader2,
  AlertTriangle,
  CheckCircle2,
  ShieldCheck,
  ShieldAlert,
  ShieldQuestion,
  ChevronRight,
  Info,
  Bot,
  User,
} from "lucide-react"
import { toast } from "sonner"

import { Button } from "@/components/ui/button"
import { Card, CardHeader, CardTitle, CardContent, CardDescription } from "@/components/ui/card"
import { Badge } from "@/components/ui/badge"
import { Progress } from "@/components/ui/progress"
import { SidebarTrigger } from "@/components/ui/sidebar"

const SUPPORTED_EXTENSIONS = [".py", ".java", ".cpp", ".js", ".c", ".cs"]

function formatBytes(bytes) {
  if (bytes === 0) return "0 B"
  const k = 1024
  const sizes = ["B", "KB", "MB"]
  const i = Math.floor(Math.log(bytes) / Math.log(k))
  return parseFloat((bytes / Math.pow(k, i)).toFixed(1)) + " " + sizes[i]
}

// ── Main Page ───────────────────────────────────────────────────
const AICheckPage = () => {
  const [file, setFile] = useState(null)
  const [analyzing, setAnalyzing] = useState(false)
  const [result, setResult] = useState(null)
  const [error, setError] = useState(null)
  const [dragOver, setDragOver] = useState(false)
  const inputRef = useRef(null)

  const handleFile = useCallback((incoming) => {
    const f = incoming[0]
    if (!f) return
    const ext = "." + f.name.split(".").pop().toLowerCase()
    if (!SUPPORTED_EXTENSIONS.includes(ext)) {
      toast.error(`Unsupported file type. Supported: ${SUPPORTED_EXTENSIONS.join(", ")}`)
      return
    }
    setFile(f)
    setResult(null)
    setError(null)
  }, [])

  const clearFile = () => {
    setFile(null)
    setResult(null)
    setError(null)
  }

  // ── Drag & drop ─────────────────────────────────────────────
  const onDragOver = (e) => { e.preventDefault(); setDragOver(true) }
  const onDragLeave = () => setDragOver(false)
  const onDrop = (e) => {
    e.preventDefault()
    setDragOver(false)
    if (e.dataTransfer.files.length) handleFile(e.dataTransfer.files)
  }

  // ── Submit ──────────────────────────────────────────────────
  const handleSubmit = async () => {
    if (!file) {
      toast.error("Please select a code file first.")
      return
    }

    setAnalyzing(true)
    setResult(null)
    setError(null)

    try {
      const formData = new FormData()
      formData.append("file", file, file.name)

      const token = localStorage.getItem("token")
      const res = await fetch("/api/code/ai_detect", {
        method: "POST",
        headers: token ? { Authorization: `Bearer ${token}` } : {},
        body: formData,
      })
      const data = await res.json()

      if (!res.ok) {
        throw new Error(data.error || `Server error ${res.status}`)
      }

      setResult(data)
      toast.success("Analysis complete.")
    } catch (err) {
      setError(err.message)
      toast.error(err.message)
    } finally {
      setAnalyzing(false)
    }
  }

  // ── Animations ──────────────────────────────────────────────
  const container = {
    hidden: { opacity: 0 },
    show: { opacity: 1, transition: { staggerChildren: 0.08 } },
  }
  const item = {
    hidden: { y: 16, opacity: 0 },
    show: { y: 0, opacity: 1 },
  }

  return (
    <div className="flex flex-col min-h-screen bg-transparent">
      {/* Header */}
      <header className="h-16 border-b bg-card/80 backdrop-blur-md flex items-center justify-between px-6 z-10 sticky top-0 shrink-0">
        <div className="flex items-center gap-4">
          <SidebarTrigger className="p-2" />
          <h1 className="text-xl font-semibold hidden sm:block">AI Code Detection</h1>
        </div>
      </header>

      <div className="flex-1 overflow-y-auto p-4 md:p-6 lg:p-8">
        <motion.div
          variants={container}
          initial="hidden"
          animate="show"
          className="max-w-3xl mx-auto space-y-6"
        >
          {/* Title */}
          <motion.div variants={item}>
            <h2 className="text-3xl font-bold tracking-tight">AI Code Detector</h2>
            <p className="text-muted-foreground mt-1">
              Upload a source code file to analyze whether it was generated by AI.
            </p>
          </motion.div>

          {/* Upload Card */}
          <motion.div variants={item}>
            <Card>
              <CardHeader className="pb-3">
                <CardTitle className="text-base">Upload Code File</CardTitle>
                <CardDescription>
                  Supported: {SUPPORTED_EXTENSIONS.join(", ")}
                </CardDescription>
              </CardHeader>
              <CardContent>
                {!file ? (
                  <div
                    id="file-drop-zone"
                    onClick={() => inputRef.current?.click()}
                    onDragOver={onDragOver}
                    onDragLeave={onDragLeave}
                    onDrop={onDrop}
                    className={`
                      relative cursor-pointer rounded-xl border-2 border-dashed p-10
                      flex flex-col items-center justify-center gap-3
                      transition-all duration-200
                      ${dragOver
                        ? "border-primary bg-primary/5 scale-[1.01]"
                        : "border-muted-foreground/25 hover:border-primary/50 hover:bg-muted/40"
                      }
                    `}
                  >
                    <motion.div
                      animate={dragOver ? { scale: 1.15, rotate: -5 } : { scale: 1, rotate: 0 }}
                      transition={{ type: "spring", stiffness: 300, damping: 20 }}
                    >
                      <div className="p-4 rounded-full bg-primary/10">
                        <Upload className="h-8 w-8 text-primary" />
                      </div>
                    </motion.div>
                    <div className="text-center">
                      <p className="font-medium">
                        {dragOver ? "Drop file here" : "Click or drag a code file here"}
                      </p>
                      <p className="text-sm text-muted-foreground mt-1">
                        Single source code file for AI detection analysis
                      </p>
                    </div>
                    <input
                      ref={inputRef}
                      type="file"
                      accept={SUPPORTED_EXTENSIONS.join(",")}
                      className="hidden"
                      onChange={(e) => {
                        if (e.target.files.length) handleFile(e.target.files)
                        e.target.value = ""
                      }}
                    />
                  </div>
                ) : (
                  <motion.div
                    initial={{ opacity: 0, y: 8 }}
                    animate={{ opacity: 1, y: 0 }}
                    className="flex items-center justify-between p-3 rounded-lg border bg-card"
                  >
                    <div className="flex items-center gap-3 min-w-0">
                      <div className="p-2 rounded-md bg-primary/10">
                        <FileCode className="h-5 w-5 text-primary" />
                      </div>
                      <div className="min-w-0">
                        <p className="text-sm font-medium truncate">{file.name}</p>
                        <p className="text-xs text-muted-foreground">{formatBytes(file.size)}</p>
                      </div>
                    </div>
                    <button
                      onClick={clearFile}
                      className="p-1.5 rounded-md hover:bg-destructive/10 transition-colors"
                    >
                      <X className="h-4 w-4 text-destructive" />
                    </button>
                  </motion.div>
                )}
              </CardContent>
            </Card>
          </motion.div>

          {/* Analyze Button */}
          <motion.div variants={item} className="flex justify-end">
            <Button
              id="analyze-btn"
              size="lg"
              disabled={analyzing || !file}
              onClick={handleSubmit}
              className="gap-2 px-8"
            >
              {analyzing ? (
                <>
                  <Loader2 className="h-4 w-4 animate-spin" />
                  Analyzing…
                </>
              ) : (
                <>
                  Analyze Code
                  <ShieldCheck className="h-4 w-4" />
                </>
              )}
            </Button>
          </motion.div>

          {/* Error */}
          <AnimatePresence>
            {error && !analyzing && (
              <motion.div
                initial={{ opacity: 0, y: 10 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0 }}
              >
                <Card className="border-destructive/50">
                  <CardContent className="pt-6 flex items-start gap-3">
                    <AlertTriangle className="h-5 w-5 text-destructive shrink-0 mt-0.5" />
                    <div>
                      <p className="font-medium text-destructive">Analysis failed</p>
                      <p className="text-sm text-muted-foreground mt-1">{error}</p>
                    </div>
                  </CardContent>
                </Card>
              </motion.div>
            )}
          </AnimatePresence>

          {/* Results */}
          <AnimatePresence>
            {result && !analyzing && (
              <motion.div
                initial={{ opacity: 0, y: 20 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0 }}
                className="space-y-4"
              >
                <ResultsPanel result={result} />
              </motion.div>
            )}
          </AnimatePresence>
        </motion.div>
      </div>
    </div>
  )
}

// ─── Results Panel ──────────────────────────────────────────────
function ResultsPanel({ result }) {
  const prob = (result.ai_probability * 100)
  const probStr = prob.toFixed(1)

  const isLikelyAI = prob >= 70
  const isPossiblyAI = prob >= 40

  const VerdictIcon = isLikelyAI ? ShieldAlert : isPossiblyAI ? ShieldQuestion : ShieldCheck
  const verdictColor = isLikelyAI
    ? "text-red-600 dark:text-red-400"
    : isPossiblyAI
      ? "text-amber-600 dark:text-amber-400"
      : "text-green-600 dark:text-green-400"
  const verdictBg = isLikelyAI
    ? "bg-red-500/8 border-red-500/25"
    : isPossiblyAI
      ? "bg-amber-500/8 border-amber-500/25"
      : "bg-green-500/8 border-green-500/25"
  const barColor = isLikelyAI
    ? "[&>div]:bg-red-500"
    : isPossiblyAI
      ? "[&>div]:bg-amber-500"
      : "[&>div]:bg-green-500"
  const ringColor = isLikelyAI
    ? "border-red-500/40"
    : isPossiblyAI
      ? "border-amber-500/40"
      : "border-green-500/40"

  // Group signals
  const signalDetails = result.signal_details || {}
  const structural = Object.entries(signalDetails).filter(([, d]) => d.group === "structural")
  const textual = Object.entries(signalDetails).filter(([, d]) => d.group === "textual")

  return (
    <>
      {/* Main verdict card */}
      <Card className={`overflow-hidden ${ringColor}`}>
        <CardContent className="pt-6 pb-5">
          <div className="flex flex-col sm:flex-row items-center gap-6">
            {/* Probability gauge */}
            <div className="flex flex-col items-center gap-2 shrink-0">
              <div className={`relative w-28 h-28 rounded-full border-4 flex items-center justify-center ${ringColor}`}>
                <div className="text-center">
                  <span className={`text-3xl font-bold font-mono tabular-nums ${verdictColor}`}>
                    {probStr}
                  </span>
                  <span className="text-xs text-muted-foreground block -mt-0.5">% AI</span>
                </div>
              </div>
            </div>

            {/* Verdict info */}
            <div className="flex-1 text-center sm:text-left space-y-2">
              <div className="flex items-center gap-2 justify-center sm:justify-start">
                <VerdictIcon className={`h-5 w-5 shrink-0 ${verdictColor}`} />
                <h3 className={`text-lg font-bold ${verdictColor}`}>{result.verdict}</h3>
              </div>
              <p className="text-sm text-muted-foreground">
                {result.file_name?.split("/").pop() || "Unknown"}{" "}
                <Badge variant="outline" className="text-[10px] font-mono ml-1 px-1.5 py-0">{result.language}</Badge>
              </p>
              <div className="w-full max-w-sm mx-auto sm:mx-0">
                <div className="flex items-center justify-between text-[11px] text-muted-foreground mb-1">
                  <span className="flex items-center gap-1"><User className="h-3 w-3" /> Human</span>
                  <span className="flex items-center gap-1">AI <Bot className="h-3 w-3" /></span>
                </div>
                <Progress value={prob} className={`h-2.5 ${barColor}`} />
              </div>
            </div>
          </div>
        </CardContent>
      </Card>

      {/* Explanations */}
      {result.explanations && result.explanations.length > 0 && (
        <Card>
          <CardHeader className="pb-2">
            <CardTitle className="text-sm">Key Findings</CardTitle>
          </CardHeader>
          <CardContent>
            <ul className="space-y-1.5">
              {result.explanations.map((exp, i) => (
                <li key={i} className="flex items-start gap-2 text-sm">
                  <Info className="h-3.5 w-3.5 mt-0.5 shrink-0 text-muted-foreground" />
                  <span>{exp}</span>
                </li>
              ))}
            </ul>
          </CardContent>
        </Card>
      )}

      {/* Signal Breakdown */}
      <Card>
        <CardHeader className="pb-2">
          <CardTitle className="text-sm">Signal Breakdown</CardTitle>
          <CardDescription className="text-xs">18 structural and textual signals analyzed</CardDescription>
        </CardHeader>
        <CardContent className="space-y-5">
          {/* Structural signals */}
          {structural.length > 0 && (
            <div>
              <p className="text-xs font-medium text-muted-foreground uppercase tracking-wider mb-3">
                Structural (AST-based)
              </p>
              <div className="space-y-2.5">
                {structural.map(([key, detail]) => (
                  <SignalBar key={key} detail={detail} />
                ))}
              </div>
            </div>
          )}

          {/* Textual signals */}
          {textual.length > 0 && (
            <div>
              <p className="text-xs font-medium text-muted-foreground uppercase tracking-wider mb-3">
                Textual (Source-level)
              </p>
              <div className="space-y-2.5">
                {textual.map(([key, detail]) => (
                  <SignalBar key={key} detail={detail} />
                ))}
              </div>
            </div>
          )}
        </CardContent>
      </Card>
    </>
  )
}

// ─── Signal Bar ─────────────────────────────────────────────────
function SignalBar({ detail }) {
  const pct = (detail.value * 100)
  const isHigh = pct >= 65
  const isMed = pct >= 40

  const barColor = isHigh
    ? "[&>div]:bg-red-500"
    : isMed
      ? "[&>div]:bg-amber-500"
      : "[&>div]:bg-green-500"

  const textColor = isHigh
    ? "text-red-600 dark:text-red-400"
    : isMed
      ? "text-amber-600 dark:text-amber-400"
      : "text-muted-foreground"

  return (
    <div className="group" title={detail.tip}>
      <div className="flex items-center justify-between mb-1">
        <span className="text-xs font-medium truncate pr-2">{detail.label}</span>
        <span className={`text-xs font-mono font-semibold tabular-nums ${textColor}`}>
          {pct.toFixed(0)}%
        </span>
      </div>
      <Progress value={Math.min(pct, 100)} className={`h-1.5 ${barColor}`} />
    </div>
  )
}

export default AICheckPage
